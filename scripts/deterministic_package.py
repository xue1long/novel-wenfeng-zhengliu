"""Stage G Task 3: deterministic directory + ZIP packaging.

Pure stdlib. Ruling-G4:

  - ZIP entries are sorted by relative path (lexicographic).
  - mtime is fixed at 1980-01-01 00:00:00 UTC (the DOS epoch that
    ``zipfile`` uses for ``ZipInfo``).
  - Mode is fixed at 0o644 for files / 0o755 for directories.
  - Compression: ``ZIP_DEFLATED``.

Same input -> same bytes.

Refuses:
  - any path that escapes the output directory;
  - any symlink (delegated to stage B ``path_safety``);
  - any standard location (``~/.wenfeng-skill``, ``%APPDATA%/wenfeng-skill``,
    ``dist/<source_id>/<bundle_version>/`` for `private-preview`).
"""

from __future__ import annotations

import hashlib
import os
import shutil
import zipfile
from datetime import datetime, timezone
from pathlib import Path
from typing import Iterable

from path_safety import PathEscapeError, assert_within_run_root, assert_no_symlink_escape


# Fixed mtime for deterministic output. 1980-01-01 00:00:00 UTC.
_FIXED_MTIME: tuple[int, int, int, int, int, int] = (1980, 1, 1, 0, 0, 0)


# Files that MUST be in the package (spec §4.9).
# Tuple shape: ``(label, relative_path_in_staging, relative_path_in_dist)``.
# The last tuple entry ``release-manifest.json`` is generated by stage G
# (not present in staging); ``build_directory_dist`` is the only place
# that is allowed to add it.
_STAGED_FILES: tuple[tuple[str, str, str], ...] = (
    ("write_entry", "write_entry/SKILL.md", "write_entry/SKILL.md"),
    ("scene_design", "scene_design/SKILL.md", "scene_design/SKILL.md"),
    ("character_beats", "character_beats/SKILL.md", "character_beats/SKILL.md"),
    ("prose_draft", "prose_draft/SKILL.md", "prose_draft/SKILL.md"),
    ("style_check", "style_check/SKILL.md", "style_check/SKILL.md"),
    ("revision", "revision/SKILL.md", "revision/SKILL.md"),
    ("compile-manifest", "compile-manifest.json", "compile-manifest.json"),
    ("eval-report", "eval-report.json", "eval-report.json"),
)


class DeterministicPackageError(Exception):
    def __init__(self, message: str, *, error_type: str = "deterministic_package_error") -> None:
        super().__init__(message)
        self.error_type = error_type


def _fixed_zipinfo(name: str, *, is_dir: bool = False) -> zipfile.ZipInfo:
    info = zipfile.ZipInfo(name)
    info.date_time = _FIXED_MTIME
    info.compress_type = zipfile.ZIP_DEFLATED
    info.external_attr = (0o755 if is_dir else 0o644) << 16
    return info


def build_directory_dist(
    staging_root: Path,
    manifest: dict,
    *,
    output_dir: Path,
    include_scan_report: bool = True,
) -> Path:
    """Copy the package-able subset of ``staging_root`` into ``output_dir``.

    Returns the produced directory. The structure is::

        output_dir/
          write_entry/SKILL.md
          scene_design/SKILL.md
          ...
          compile-manifest.json
          eval-report.json
          release-manifest.json
          source-scan-report.json  (optional)
    """
    staging_root = Path(staging_root).resolve()
    output_dir = Path(output_dir).resolve()
    if output_dir.exists() and any(output_dir.iterdir()):
        raise DeterministicPackageError(
            f"output_dir {output_dir} is non-empty; refuse to overwrite"
        )
    if output_dir.exists():
        output_dir.mkdir(parents=True, exist_ok=True)
    else:
        output_dir.mkdir(parents=True)
    # Walk the staging_root and copy only the allow-listed files.
    for _, src_rel, dst_rel in _STAGED_FILES:
        src = staging_root / src_rel
        if not src.is_file():
            raise DeterministicPackageError(f"staging missing {src_rel}")
        try:
            assert_within_run_root(staging_root, src)
        except PathEscapeError as exc:
            raise DeterministicPackageError(str(exc)) from exc
        dst = output_dir / dst_rel
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(src, dst)
        # Force mtime to fixed value for determinism.
        fixed = datetime(*_FIXED_MTIME[:6], tzinfo=timezone.utc).timestamp()
        os.utime(dst, (fixed, fixed))
    if include_scan_report:
        scan_path = staging_root / "source-scan-report.json"
        if scan_path.is_file():
            dst = output_dir / "source-scan-report.json"
            shutil.copy2(scan_path, dst)
            fixed = datetime(*_FIXED_MTIME[:6], tzinfo=timezone.utc).timestamp()
            os.utime(dst, (fixed, fixed))
    return output_dir


def build_zip_dist(
    directory_dist: Path,
    output_path: Path,
) -> Path:
    """Build a deterministic ZIP from ``directory_dist``.

    Refuses symlinks anywhere inside ``directory_dist`` and refuses any
    path that escapes it.
    """
    directory_dist = Path(directory_dist).resolve()
    output_path = Path(output_path).resolve()
    if output_path.exists():
        raise DeterministicPackageError(
            f"output_path {output_path} already exists; refuse to overwrite"
        )
    if not directory_dist.is_dir():
        raise DeterministicPackageError(
            f"directory_dist {directory_dist} is not a directory"
        )
    # Walk first; collect entries in lexicographic order.
    paths: list[Path] = []
    # release-manifest.json is excluded from the ZIP: it lives at
    # dist_dir root alongside package.zip, and includes the ZIP's own
    # hash. Including it would create a bootstrapping loop.
    EXCLUDED_FROM_ZIP = {"release-manifest.json"}
    for path in sorted(directory_dist.rglob("*")):
        if path.is_dir():
            continue
        rel = path.relative_to(directory_dist).as_posix()
        if rel in EXCLUDED_FROM_ZIP:
            continue
        try:
            assert_no_symlink_escape(path)
        except PathEscapeError as exc:
            raise DeterministicPackageError(str(exc)) from exc
        try:
            assert_within_run_root(directory_dist, path)
        except PathEscapeError as exc:
            raise DeterministicPackageError(str(exc)) from exc
        paths.append(path)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(output_path, "w") as zf:
        for path in paths:
            rel = path.relative_to(directory_dist).as_posix()
            info = _fixed_zipinfo(rel)
            zf.writestr(info, path.read_bytes())
    return output_path


def compute_zip_hash(zip_path: Path) -> str:
    return hashlib.sha256(zip_path.read_bytes()).hexdigest()


